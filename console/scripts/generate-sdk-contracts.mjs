import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compileFromFile } from "json-schema-to-typescript";
import { format } from "prettier";

const consoleRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(consoleRoot, "..");
const schemaRoot = resolve(repositoryRoot, "schemas", "sdk");
const outputRoot = resolve(
  repositoryRoot,
  "packages",
  "qwenpaw-client",
  "src",
  "generated",
);
const contracts = [
  ["host-handshake", "hostHandshake.ts"],
  ["interaction-request", "interactionRequest.ts"],
  ["interaction-resolution", "interactionResolution.ts"],
  ["chat-control-request", "chatControlRequest.ts"],
  ["chat-steer-request", "chatSteerRequest.ts"],
  ["chat-queue-reorder-request", "chatQueueReorderRequest.ts"],
  ["chat-submission-request", "chatSubmissionRequest.ts"],
  ["control-receipt", "controlReceipt.ts"],
  ["queue-projection", "queueProjection.ts"],
  ["task-projection", "taskProjection.ts"],
  ["action-record", "actionRecord.ts"],
  ["conversation-artifact-record", "conversationArtifactRecord.ts"],
  ["observation-page", "observationPage.ts"],
  ["conversation-trajectory-page", "conversationTrajectoryPage.ts"],
  ["model-call-record", "modelCallRecord.ts"],
  ["wait-condition", "waitCondition.ts"],
];
const checkOnly = process.argv.includes("--check");
const stale = [];

if (!checkOnly) await mkdir(outputRoot, { recursive: true });
for (const [schemaName, outputName] of contracts) {
  const source = resolve(schemaRoot, `${schemaName}.schema.json`);
  const compiled = await compileFromFile(source, {
    additionalProperties: false,
    bannerComment:
      "/* Generated from schemas/sdk. Do not edit this file directly. */",
    style: {
      bracketSpacing: true,
      printWidth: 79,
      semi: true,
      singleQuote: false,
      tabWidth: 2,
      trailingComma: "all",
      useTabs: false,
    },
  });
  const output = await format(compiled, {
    parser: "typescript",
    printWidth: 79,
    semi: true,
    singleQuote: false,
    trailingComma: "all",
  });
  const outputPath = resolve(outputRoot, outputName);
  if (checkOnly) {
    const committed = await readFile(outputPath, "utf8").catch(() => "");
    if (committed !== output) stale.push(outputName);
  } else {
    await writeFile(outputPath, output, "utf8");
  }
}

if (stale.length > 0) {
  throw new Error(
    `Generated SDK contracts are stale: ${stale.join(", ")}. ` +
      "Run npm run contracts:generate.",
  );
}
